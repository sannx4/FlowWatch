-- FlowWatch Day25: apply ONLY to flowwatch_day25_gate during acceptance.
-- Versioned DDL; follow-up Alembic migration is generated using the included helper.
BEGIN;
CREATE TABLE IF NOT EXISTS public.source_quarantine (
    quarantine_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_run_id uuid NOT NULL,
    source_record_key text NOT NULL,
    source_checksum char(64) NOT NULL,
    page_number integer NOT NULL CHECK (page_number >= 0),
    page_offset integer NOT NULL CHECK (page_offset >= 0),
    record_index integer NOT NULL CHECK (record_index >= 0),
    rule_id text NOT NULL CHECK (btrim(rule_id) <> ''),
    offending_field text NOT NULL CHECK (btrim(offending_field) <> ''),
    offending_value jsonb,
    failure_detail text NOT NULL,
    failed_parser_version text NOT NULL,
    status text NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'BLOCKED', 'RESOLVED')),
    occurrences integer NOT NULL DEFAULT 1 CHECK (occurrences > 0),
    retry_count integer NOT NULL DEFAULT 0 CHECK (retry_count >= 0),
    first_seen_at timestamptz NOT NULL DEFAULT now(),
    last_seen_at timestamptz NOT NULL DEFAULT now(),
    last_retry_at timestamptz,
    resolved_at timestamptz,
    resolved_parser_version text,
    resolved_snapshot_id bigint REFERENCES public.credit_snapshots(credit_snapshot_id)
        ON DELETE RESTRICT,
    last_error text,
    CONSTRAINT uq_source_quarantine_identity UNIQUE
        (source_run_id, source_record_key, rule_id, failed_parser_version),
    CONSTRAINT ck_source_quarantine_resolution CHECK (
        (status = 'RESOLVED' AND resolved_at IS NOT NULL
          AND resolved_parser_version IS NOT NULL AND resolved_snapshot_id IS NOT NULL)
        OR (status <> 'RESOLVED' AND resolved_at IS NULL
          AND resolved_parser_version IS NULL AND resolved_snapshot_id IS NULL)
    )
);
CREATE INDEX IF NOT EXISTS ix_source_quarantine_state
    ON public.source_quarantine(status, last_seen_at);
CREATE INDEX IF NOT EXISTS ix_source_quarantine_source
    ON public.source_quarantine(source_run_id, source_record_key);
GRANT SELECT, INSERT, UPDATE ON TABLE public.source_quarantine TO flowwatch_ingestor;
GRANT USAGE, SELECT ON SEQUENCE public.source_quarantine_quarantine_id_seq TO flowwatch_ingestor;
COMMIT;
